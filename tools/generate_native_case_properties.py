"""Regenerate the optional reasoning detector's Python 3.13 Unicode casing rules.

This is a development tool; the native runtime only uses the generated C++ data.
Python's contextual Sigma conversion supplies Case_Ignorable membership without
requiring private CPython exports or another Unicode library.
"""
from pathlib import Path
import re
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
if unicodedata.unidata_version != "15.1.0":
    raise SystemExit("use Python with Unicode 15.1.0 (the Python 3.13 reference)")

vendor = (ROOT / "third_party/llama.cpp/src/unicode-data.cpp").read_text(encoding="utf-8")
table = vendor.split("unicode_map_lowercase = {", 1)[1].split("};", 1)[0]
lower = {int(a, 16): int(b, 16) for a, b in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", table)}
properties = {"cased": [], "ignorable": []}
for cp in range(0x110000):
    char = chr(cp)
    if lower.get(cp, cp) != ord(char.lower()[0]):
        raise SystemExit(f"vendor lowercase table differs from the reference at U+{cp:04X}")
    cased = char.islower() or char.isupper() or char.istitle()
    ignorable = ((char + "Σ").lower()[-1] == "σ" if cased
                 else ("AΣ" + char + "A").lower()[1] == "σ")
    properties["cased"].append(cased)
    properties["ignorable"].append(ignorable)

lines = ["// Generated by tools/generate_native_case_properties.py; Unicode 15.1.0.",
         "#pragma once", "#include <cstdint>", "namespace strata::runtime::case_properties {",
         "struct Range { uint32_t first, last; };"]
for name, values in properties.items():
    ranges, start = [], None
    for cp, present in enumerate(values + [False]):
        if present and start is None:
            start = cp
        elif not present and start is not None:
            ranges.append((start, cp - 1)); start = None
    lines.append(f"inline constexpr Range {name}[] = {{")
    lines += [f"    {{0x{first:06x}, 0x{last:06x}}}," for first, last in ranges]
    lines.append("};")
    print(name, len(ranges), "ranges")
lines.append("} // namespace strata::runtime::case_properties")
(ROOT / "src/runtime/server_case_properties.hpp").write_text("\n".join(lines) + "\n", encoding="utf-8")
